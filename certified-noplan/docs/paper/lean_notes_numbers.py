#!/usr/bin/env python3
"""L4-bis — regenerate section (d) "Numbers" of docs/paper/LEAN-NOTES.md from archived runs.

    python3 docs/paper/lean_notes_numbers.py <…/lean_kernel_bench.json> <…/lean_parity.json>

Every figure of the new (d) is READ from a file, none is retyped: the two quiet-machine JSON
given on the command line (written by ``benchmarks/lean_quiet_bench.py``), the earlier archived
runs they are compared with (the L4 kernel runs, the L4 and L1 parity logs) and, for what is not
a measurement of this machine (sizes, axioms, CI, the failures established in L4), the previous
(d) — kept verbatim as an annex at the end of the file the first time this script runs, and from
which those paragraphs and table cells are copied. Idempotent.

Prints the quiet-versus-L4 comparison table on stdout (it goes to the journal as printed).
"""
from __future__ import annotations

import importlib.util
import json
import os
import re
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
RESULTS = os.path.join(ROOT, "benchmarks", "results")
NOTES = os.path.join(HERE, "LEAN-NOTES.md")
HEAD, TAIL = "## (d) Numbers\n", "\n---\n\n## (e)"
ANNEX = "## Annex — section (d) as written in L4, on a machine under load (superseded)\n"
ANNEX_NOTE = (
    "*Kept verbatim for traceability (L4 review, decision 7: no L4 timing is quoted before the\n"
    "replay on a quiet machine). Every timing below was taken with a game running on two of the\n"
    "ten cores; the current figures are in (d). The failure cells of the table and the paragraphs\n"
    "Size, Axioms and CI remain the reference: `docs/paper/lean_notes_numbers.py` copies them\n"
    "from here into (d).*\n")
L4_PRIMITIVES_RUN, L4_PARITY_RUN, L1_PARITY_RUN = "20261010T172639Z", "20261010T173121Z", "20261009T214354Z"


def quiet_bench():
    spec = importlib.util.spec_from_file_location(
        "lean_quiet_bench", os.path.join(ROOT, "benchmarks", "lean_quiet_bench.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def run_of(path: str) -> str:
    return os.path.basename(os.path.dirname(os.path.abspath(path)))


def rel(path: str) -> str:
    return os.path.relpath(os.path.abspath(path), ROOT)


def load1(log_header: dict) -> str:
    return log_header["load average at start"].strip("{} ").split()[0]


def carried(pars: list, prefix: str, n: int = 1) -> str:
    i = next(i for i, p in enumerate(pars) if p.startswith(prefix))
    return "\n\n".join(pars[i:i + n])


def l4_cells(annex: str) -> dict:
    """certificate -> the 8 cells of its row in the L4 table."""
    out = {}
    for ln in annex.splitlines():
        cells = [c.strip() for c in ln.strip().strip("|").split("|")]
        if ln.startswith("| `scenes/") and len(cells) == 8:
            out[cells[0].strip("`")] = cells
    return out


def ratio(a: float, b: float) -> str:
    return f"×{a / b:.2f}" if b else "—"


def main() -> int:
    kernel_path, parity_path = sys.argv[1], sys.argv[2]
    kb = json.load(open(kernel_path, encoding="utf-8"))
    par = json.load(open(parity_path, encoding="utf-8"))
    q = quiet_bench()

    with open(NOTES, encoding="utf-8") as f:
        text = f.read()
    start, end = text.index(HEAD), text.index(TAIL)
    if ANNEX not in text:                                  # first run: keep the L4 section
        text = text.rstrip("\n") + "\n\n---\n\n" + ANNEX + "\n" + ANNEX_NOTE + "\n" \
            + text[start + len(HEAD):end].strip("\n") + "\n"
    annex = text[text.index(ANNEX) + len(ANNEX):]
    pars = re.split(r"\n\s*\n", annex.strip())
    cells = l4_cells(annex)

    # earlier archived runs, for comparison
    l4 = {}
    for ts in kb["l4_failure_runs"]:                       # a later run supersedes (S6)
        for r in json.load(open(os.path.join(RESULTS, ts, "lean_kernel.json"), encoding="utf-8"))["rows"]:
            l4[r["certificate"]] = (ts, r)
    l4_prim = {p["primitive"]: p for p in json.load(
        open(os.path.join(RESULTS, L4_PRIMITIVES_RUN, "lean_kernel.json"), encoding="utf-8"))["primitives"]}
    logs = {}
    for ts in (L4_PARITY_RUN, L1_PARITY_RUN):
        with open(os.path.join(RESULTS, ts, "lean_parity.log"), encoding="utf-8") as f:
            logs[ts] = q.parse_parity_log(f.read())
    p4, p1 = logs[L4_PARITY_RUN], logs[L1_PARITY_RUN]

    km, pm = kb["meta"], par["meta"]
    k3 = next(r for r in kb["rows"] if r["staged"])
    st, whole, nd3 = k3["staged"], k3["staged"]["whole_file"], k3["native_decide"]
    l4k3 = l4[k3["certificate"]][1]
    l4whole = l4k3["staged"]["whole_file"]
    heaviest = max(st["stages"], key=lambda s: s["peak_rss_gb"])

    out = [HEAD]
    out += [f"*Regenerated by `docs/paper/lean_notes_numbers.py` (session L4-bis) from\n"
            f"`{rel(kernel_path)}` and\n`{rel(parity_path)}`: every figure below is read from an\n"
            "archived file, none is retyped. The paragraphs **Size**, **Axioms** and **CI**, and the\n"
            "cells marked † of the kernel table, are not measurements of this session: they are copied\n"
            "from the L4 section, kept verbatim as the annex at the end of this file.*", ""]
    out += [f"**Versions.** {km['lean']}; {km['lake']}; Mathlib `{km['mathlib']}` (commit "
            f"`{km['mathlib_commit'][:8]}…`).", ""]
    out += [f"**Machine.** {km['machine']}. **Quiet**: each run starts only once the 1-minute load "
            f"average is below {km['max_load']:g}, on a clean tree.", "",
            "| run | commit | `uptime` before | `uptime` after |", "|---|---|---|---|",
            f"| kernel bench `{run_of(kernel_path)}` | `{km['commit'][:7]}` | `{km['before']['uptime']}` | "
            f"`{km['after']['uptime']}` |",
            f"| parity `{run_of(parity_path)}` | `{pm['commit'][:7]}` | `{pm['before']['uptime']}` | "
            f"`{pm['after']['uptime']}` |", ""]
    loads = [s["load1_at_start"] for s in st["stages"]] + [whole["load1_at_start"]] \
        + [r["native_decide"]["load1_at_start"] for r in kb["rows"]]
    out += [f"The gate is on the load BEFORE each run. During the kernel run the 1-minute load, read at "
            f"the start of each probe, lies between {min(loads)} and {max(loads)}: the bench is itself one "
            f"`lean` process at full speed (up to {kb['k3_staged_peak_rss_gb']:.2f} GiB allocated, then "
            "released, per probe) and a memory probe at 5 Hz, on ten cores; the session started nothing "
            f"else. The two passes over the same {st['n_stages']} kernel evaluations, minutes apart, agree: "
            f"{st['sum_kernel_s']} s of kernel time for the stages alone, {whole['kernel_s']:.1f} s for the "
            f"whole file. The parity log's own `load average at start` ({load1(par['log_header'])}) is read "
            "later than the gate, after `lean/check_all.sh` has checked the build and exported the corpus.", ""]
    out += [carried(pars, "**Size**", 2), "", carried(pars, "**Axioms**"), ""]

    out += [f"**Kernel evaluation, quiet machine** — `benchmarks/lean_quiet_bench.py kernel`, run "
            f"`{run_of(kernel_path)}`: the probes of `scripts/lean_kernel_bench.py` (same code, one "
            f"process per probe, killed beyond {km['mem_gb']:g} GiB of resident memory, 1 GiB = 2³⁰ bytes). "
            "† = cell of the L4 table, NOT replayed: " + kb["not_rerun"].split(", not re-run: ")[1]
            + f" ({kb['not_rerun'].split(', not re-run')[0]}) — a failure by transparency or by memory "
            "does not depend on the load.", "",
            "| certificate | n | leaves (collision / outside) | body vertices | `by decide` † | "
            "`by decide +kernel`, one evaluation † | staged kernel proof | `by native_decide` (one axiom more) |",
            "|---|---|---|---|---|---|---|---|"]
    for r in kb["rows"]:
        c, nd = cells[r["certificate"]], r["native_decide"]
        if r["staged"]:
            s, w = r["staged"], r["staged"]["whole_file"]
            staged = (f"**proved** — {s['n_stages']} stages, {w['wall_s']:.1f} s for the file "
                      f"(kernel {w['kernel_s']:.1f} s), peak {w['peak_rss_gb']:.2f} GiB")
        else:
            staged = c[6] + " †"
        out.append(f"| `{r['certificate']}` | {r['n']} | {r['leaves']} ({r['collision_leaves']} / "
                   f"{r['outside_leaves']}) | {r['hull_vertices']} | {c[4]} | {c[5]} | {staged} | "
                   f"{nd['wall_s']:.1f} s (evaluation {nd['evaluation_s']:.2f} s) |")
    out += ["", f"The staged proof of `check wallK3 = true` as built — the whole generated file in one "
            f"process: **{whole['wall_s']:.1f} s** of wall-clock time, of which {whole['kernel_s']:.1f} s in "
            f"the kernel, peak resident memory **{whole['peak_rss_gb']:.2f} GiB** (load average at start "
            f"{whole['load1_at_start']}). The same {st['n_stages']} stages, one process each: "
            f"{st['stages_passed']} pass, {st['sum_kernel_s']} s of kernel time in total, heaviest stage "
            f"`{heaviest['stage']}` ({heaviest['kernel_s']:.1f} s, {heaviest['peak_rss_gb']:.2f} GiB). Peak of "
            f"the staged proof above 8 GiB: **{'yes' if kb['k3_staged_peak_over_8_gib'] else 'no'}** "
            f"({kb['k3_staged_peak_rss_gb']:.2f} GiB). The proof measured is the shipped "
            f"`lean/Certs/WallK3Kernel.lean` (generator output identical to the file: "
            f"{'yes' if st['generated_equals_shipped_file'] else 'NO'}). Axioms of the staged proof: "
            f"{', '.join('`' + a + '`' for a in whole['axioms'])}. Axioms of `by native_decide` on the same "
            f"statement: {', '.join('`' + a + '`' for a in nd3['axioms'])}. Wall-clock figures include "
            "loading the imports (" + ", ".join(f"{r['import_only']['wall_s']} s" for r in kb["rows"])
            + ").", ""]

    # quiet versus L4
    cmp_rows = [("k3, staged proof, whole file — wall-clock", f"{whole['wall_s']:.1f} s", whole["load1_at_start"],
                 f"{l4whole['wall_s']:.1f} s", l4whole["load1_at_start"], ratio(whole["wall_s"], l4whole["wall_s"])),
                ("k3, staged proof, whole file — kernel time", f"{whole['kernel_s']:.1f} s", whole["load1_at_start"],
                 f"{l4whole['kernel_s']:.1f} s", l4whole["load1_at_start"], ratio(whole["kernel_s"], l4whole["kernel_s"])),
                ("k3, staged proof, whole file — peak memory", f"{whole['peak_rss_gb']:.2f} GiB",
                 whole["load1_at_start"], f"{l4whole['peak_rss_gb']:.2f} GiB", l4whole["load1_at_start"],
                 ratio(whole["peak_rss_gb"], l4whole["peak_rss_gb"])),
                (f"k3, {st['n_stages']} stages alone — sum of kernel time", f"{st['sum_kernel_s']} s",
                 st["stages"][0]["load1_at_start"], f"{l4k3['staged']['sum_kernel_s']} s",
                 l4k3["staged"]["stages"][0]["load1_at_start"],
                 ratio(st["sum_kernel_s"], l4k3["staged"]["sum_kernel_s"]))]
    for r in kb["rows"]:
        nd, (ts, o) = r["native_decide"], l4[r["certificate"]]
        on = o["native_decide"]
        cmp_rows.append((f"`native_decide`, `{r['certificate']}` — wall-clock (evaluation)",
                         f"{nd['wall_s']:.1f} s ({nd['evaluation_s']:.2f} s)", nd["load1_at_start"],
                         f"{on['wall_s']:.1f} s ({on['evaluation_s']:.2f} s)", on["load1_at_start"],
                         ratio(nd["wall_s"], on["wall_s"])))
    pt, p4t = par["timing"], p4["timing"]
    cmp_rows += [("parity, 13 certificates — `verify.py`, total", f"{pt['python_s_total']:.1f} s",
                  pm["before"]["loadavg"][0], f"{p4t['python_s_total']:.1f} s", load1(p4["log_header"]),
                  ratio(pt["python_s_total"], p4t["python_s_total"])),
                 ("parity, 13 certificates — `cnp-verify` (Lean), total", f"{pt['lean_s_total']:.1f} s",
                  pm["before"]["loadavg"][0], f"{p4t['lean_s_total']:.1f} s", load1(p4["log_header"]),
                  ratio(pt["lean_s_total"], p4t["lean_s_total"]))]
    cmp_md = ["| measurement | L4-bis, quiet | load (1 min) at start | L4, under load | load (1 min) at start | "
              "quiet / L4 |", "|---|---|---|---|---|---|"]
    cmp_md += [f"| {a} | {b} | {c} | {d} | {e} | {f} |" for a, b, c, d, e, f in cmp_rows]
    out += ["Quiet machine against the L4 runs (`" + "`, `".join(
        kb["l4_failure_runs"] + [L4_PARITY_RUN]) + "`; L4 also built the file twice more with `lake "
        "build`, figures not archived as JSON — see the annex):", ""] + cmp_md + [""]

    out += [f"Stages of the proof of `check wallK3 = true`, one process each (run `{run_of(kernel_path)}`):", "",
            "| stage | kernel s | peak GiB |", "|---|---|---|"]
    out += [f"| `{s['stage']}` | {s['kernel_s']:.1f} | {s['peak_rss_gb']:.1f} |" for s in st["stages"]]
    out += ["", "What the kernel pays for the array operations the checker is written with — `by decide "
            "+kernel` on one operation over an array of N naturals, kernel seconds (same run; last column: "
            f"the ratio measured under load in L4, run `{L4_PRIMITIVES_RUN}`):", "",
            "| operation | N = 125 | N = 625 | ratio | ratio in L4 |", "|---|---|---|---|---|"]
    for p in kb["primitives"]:
        a, b, o = p["125"], p["625"], l4_prim[p["primitive"]]
        out.append(f"| `{p['primitive']}` | {a['kernel_s']:.3f} s | {b['kernel_s']:.3f} s | "
                   f"×{b['kernel_s'] / a['kernel_s']:.0f} | ×{o['625']['kernel_s'] / o['125']['kernel_s']:.0f} |")

    s, fz = par["summary"], par["fuzz"]
    agree = carried(pars, "**Agreement with `verify.py`**")
    kept = re.search(r"The binary is byte-identical.*", agree, re.S).group(0)
    out += ["", f"**Agreement with `verify.py`** (measured, not proved): `benchmarks/lean_quiet_bench.py "
            f"parity` = `ARCHIVE=1 make lean-parity`, archived run `{rel(parity_path)}` (commit "
            f"`{pm['commit'][:7]}`, clean tree; log beside it): {s['shipped']} shipped certificates, PROOF on "
            f"both sides; adversarial corpus, {s['corpus_rejected']} rejected + {s['corpus_accepted']} "
            f"accepted, same verdict and same reason ({s['corpus_rows_ok']} rows of {s['corpus_rows']}); "
            f"seeded differential fuzz (seed {fz['seed']}), {fz['cases']} cases: {fz['both_proof']} PROOF on "
            f"both sides, {fz['both_reject']} REJECT on both sides, {fz['python_raises_lean_rejects']} where "
            f"Python raises and Lean rejects, {fz['lean_stricter_at_parsing']} where Lean is stricter at "
            f"parsing, **{fz['verdict_divergences']} verdict divergence** ({s['divergences']} on the "
            f"certificates and the corpus). {kept}", ""]
    out += [f"Time of the two checkers on the {s['shipped']} shipped certificates, quiet machine (`Python s`: "
            "`verify.py` in process; `Lean s`: the time `cnp-verify` reports; `Lean wall s`: its process, "
            "start-up included). Last two columns: the same ratio in the earlier runs, under load "
            f"(L4 `{L4_PARITY_RUN}`, load {load1(p4['log_header'])}; L1 `{L1_PARITY_RUN}`, load "
            f"{load1(p1['log_header'])}).", "",
            "| certificate | Python s | Lean s | Lean wall s | Lean/Python | in L4 | in L1 |",
            "|---|---|---|---|---|---|---|"]
    old4 = {r["certificate"]: r for r in p4["shipped"]}
    old1 = {r["certificate"]: r for r in p1["shipped"]}
    for r in par["shipped"]:
        c = r["certificate"]
        out.append(f"| `{c}` | {r['python_s']:.3f} | {r['lean_s']:.3f} | {r['lean_wall_s']:.3f} | "
                   f"×{r['lean_over_python']:.2f} | ×{old4[c]['lean_over_python']:.2f} | "
                   f"×{old1[c]['lean_over_python']:.2f} |")
    p1t = p1["timing"]
    out += [f"| **total** | {pt['python_s_total']:.3f} | {pt['lean_s_total']:.3f} | | "
            f"×{pt['lean_over_python_total']:.2f} | ×{p4t['lean_over_python_total']:.2f} | "
            f"×{p1t['lean_over_python_total']:.2f} |", "",
            f"Lean/Python on a quiet machine: ×{pt['lean_over_python_min']:.2f} to "
            f"×{pt['lean_over_python_max']:.2f} over the {s['shipped']} certificates (geometric mean "
            f"×{pt['lean_over_python_geomean']:.2f}; on the totals ×{pt['lean_over_python_total']:.2f}). "
            f"In L1, the run the draft's ratio comes from: ×{p1t['lean_over_python_min']:.2f} to "
            f"×{p1t['lean_over_python_max']:.2f} (geometric mean ×{p1t['lean_over_python_geomean']:.2f}).", ""]
    out += [carried(pars, "**CI**"), ""]

    text = text[:start] + "\n".join(out) + text[end:]
    with open(NOTES, "w", encoding="utf-8") as f:
        f.write(text)
    print("\n".join(cmp_md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
